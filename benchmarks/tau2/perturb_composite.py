"""Composite (k-fault) perturbation runner for the tau2 domains.

Same generate -> extract -> admit pipeline as perturb_run_{airline,retail}.py, but each
cell is (tree, combo) with K fault types applied to ONE query instead of one. Verification
is the single-fault machinery applied jointly -- see
pipeline/src/intent_graph/runtime/genverify_composite.py and
docs/composite-perturbation-howto.md.

Output shape matches the domain's existing sample files ({"summary", "results"}), so the
downstream episode runners read it without modification. Nothing in the single-fault path
is touched; the LLM cache is namespaced by prompt_version so composite generations cannot
be served into single-fault runs.

Supply note (ruling 2026-08-26): these corpora are far smaller than WebShop's (retail 98
trees, airline 58), so a tree contributes SEVERAL composites -- distinct fault mixes and
distinct slot assignments of the same task. Capacity is ample (median tree admits ~57k
distinct k=4 configurations), but episodes are not independent: cluster by tree when
analysing.
"""
import argparse
import json
import os
import random
import sys
import threading
import time
from collections import Counter
from pathlib import Path

WS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, WS + "/../../pipeline/src")
os.environ["TAU2_SRC"] = WS + "/tau2-bench/src"
os.environ["TAU2_DATA"] = WS + "/tau2-bench/data/tau2"
os.environ.setdefault("LITELLM_LOCAL_MODEL_COST_MAP", "True")
if "ARK_API_KEY" not in os.environ:
    _envf = os.path.join(WS, "..", ".env")
    if os.path.exists(_envf):
        os.environ["ARK_API_KEY"] = [l.split("=", 1)[1].strip() for l in
                                     open(_envf)
                                     if l.startswith("ARK_API_KEY=")][0]

import airline_compat  # noqa: F401,E402  (tree->graph rename shim)
from loguru import logger as _loguru      # noqa: E402
_loguru.remove()

from intent_tree import storage                                     # noqa: E402
from intent_tree.executors.tau2_inproc import Tau2Executor          # noqa: E402
from intent_tree.runtime import genverify_composite as gc           # noqa: E402
from intent_tree.runtime.llm import LLMClient                       # noqa: E402

DRAW_SEED = "composite-tau2-2026-08-26"

# Per-domain model allocation, copied verbatim from each domain's single-fault build so
# the composite corpus is generated by the SAME pair that made its single-fault corpus.
DOMAIN = {
    "airline": {
        "adapter": "intent_tree.adapters.tau2_airline:Tau2AirlineAdapter",
        "trees": "artifacts/trees/tau2_airline",
        "model": "doubao-seed-2-1-pro-260628",
        "agent_model": "doubao-seed-2-1-turbo-260628",
    },
    "retail": {
        "adapter": "intent_tree.adapters.tau2_retail:Tau2RetailAdapter",
        "trees": "artifacts/trees/tau2_retail",
        "model": "doubao-seed-2-0-pro-260215",
        "agent_model": "deepseek-v4-pro-260425",
    },
}


def llm_cfg(dom: str) -> dict:
    d = DOMAIN[dom]
    return {
        "base_url": "https://ark.cn-beijing.volces.com/api/v3",
        "model": d["model"], "agent_model": d["agent_model"],
        "agent_model_fallback": None, "api_key_env": "ARK_API_KEY",
        "max_output_tokens": 4000, "disable_thinking": True,
        "temperature_render": 0.7, "temperature_phrase": 0.3, "temperature_select": 0.0,
        "temperature_agent_act": 0.7, "temperature_agent_audit": 0.0,
        "temperature_agent_sample": 1.0, "temperature_agent_judge": 0.0,
        "reasoning_effort": "", "timeout_s": 90, "sdk_max_retries": 2,
        "cache_dir": WS + "/artifacts/llm_cache",
        # distinct namespace: composite prompts must never serve into single-fault runs
        "prompt_version": "tau2-composite-v1", "offline": False,
    }


_local = threading.local()


def session_for(adapter, executor):
    s = getattr(_local, "session", None)
    if s is None:
        s = executor.open(adapter.env_spec(adapter.ENV_KEY))
        s.__enter__()
        _local.session = s
    return s


_drop_cache: dict = {}
_drop_lock = threading.Lock()


_alt_cache: dict = {}


def alts_for(tree, adapter, sess):
    """Legal alternative values per slot, from the adapter's own domain listing.

    The environment validates writes, so a falsified value must still be LEGAL to yield a
    different state instead of an exception (measured: reading_not_executable was the
    dominant airline k=4 verdict). Slots with no listed domain simply get none.
    """
    with _drop_lock:
        hit = _alt_cache.get(tree.tree_id)
    if hit is not None:
        return hit
    out = {}
    for slot, _op, v in tree.root.conditions:
        try:
            dom = [d for d in adapter.domains(slot, tree.root.base, sess)
                   if str(d) != str(v)]
        except Exception:
            dom = []
        if dom:
            out[str(slot)] = dom[:6]
    with _drop_lock:
        _alt_cache[tree.tree_id] = out
    return out


def droppable_for(tree, adapter, sess):
    """Slots whose removal actually changes the outcome -- computed once per tree.

    Airline fills defaults for unstated arguments, so many withheld readings land on the
    true state and can never admit. Testing once here stops the writer burning attempts
    on them (measured: insufficient_information 0.21 on airline singles)."""
    with _drop_lock:
        hit = _drop_cache.get(tree.tree_id)
    if hit is not None:
        return hit
    try:
        d = gc.consequential_drops(tree.root, tree.root.conditions, adapter, sess)
    except Exception:
        d = {str(s) for s, _o, _v in tree.root.conditions}
    with _drop_lock:
        _drop_cache[tree.tree_id] = d
    return d


def run_cell(args):
    tree, combo_idx, k, adapter, executor, llm, attempts = args
    rng = random.Random(f"{tree.tree_id}:{k}:{combo_idx}:{DRAW_SEED}")
    _sess0 = session_for(adapter, executor)
    drops = droppable_for(tree, adapter, _sess0)
    alts = alts_for(tree, adapter, _sess0)
    combo = gc.draw_combo(rng, tree.root.conditions, k, adapter=adapter,
                          droppable=drops, alts=alts)
    if combo is None:
        return {"tree": tree.tree_id, "k": k, "combo_idx": combo_idx,
                "status": "skipped", "verdict": "no_feasible_combo"}
    ids = [s.id for s in combo]
    sess = session_for(adapter, executor)
    trace: list = []
    t0 = time.time()
    try:
        ctx = ""
        fn = getattr(adapter, "render_context", None)
        if fn is not None:
            try:
                ctx = fn(tree.root.base) or ""
            except Exception:
                ctx = ""
        payload = gc.build_composite_mask(
            tree, combo, llm=llm, adapter=adapter, executor=executor, session=sess,
            context=ctx, dual_extract=True, attempts=attempts, trace=trace,
            droppable=drops, alts=alts)
        return {"tree": tree.tree_id, "k": k, "combo_idx": combo_idx,
                "strategy": "+".join(ids), "strategy_ids": ids, "status": "admitted",
                "query": payload["query"], "mask": payload["mask"],
                "signature": payload.get("signature"), "attempts": len(trace),
                "sec": round(time.time() - t0, 1),
                "root_conditions": [list(c) for c in tree.root.conditions],
                "writes": tree.root.base.get("writes")}
    except gc.Rejected as e:
        return {"tree": tree.tree_id, "k": k, "combo_idx": combo_idx,
                "strategy": "+".join(ids), "status": "rejected", "verdict": e.verdict,
                "attempts": len(trace), "sec": round(time.time() - t0, 1),
                "last_text": (trace[-1]["text"] if trace else None)}
    except Exception as e:
        return {"tree": tree.tree_id, "k": k, "combo_idx": combo_idx,
                "strategy": "+".join(ids), "status": "error",
                "verdict": f"{type(e).__name__}: {str(e)[:200]}",
                "sec": round(time.time() - t0, 1)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", required=True, choices=sorted(DOMAIN))
    ap.add_argument("--k", type=int, required=True, choices=(2, 4))
    ap.add_argument("--target", type=int, default=200, help="admitted samples wanted")
    ap.add_argument("--workers", type=int, default=12)
    ap.add_argument("--attempts", type=int, default=5)
    ap.add_argument("--combos-per-tree", type=int, default=12,
                    help="distinct fault mixes drawn per tree per wave")
    ap.add_argument("--min-conditions", type=int, default=3,
                    help="condition-band floor; k=4 on a 2-condition task is degenerate")
    ap.add_argument("--max-conditions", type=int, default=12,
                    help="band ceiling; 4 faults on a 31-condition task perturb 13% of it")
    ap.add_argument("--max-waves", type=int, default=12)
    ap.add_argument("--tree-shard", default="", help="i/n: process only banded trees with index %% n == i (process-level parallelism; each shard needs its own --out)")
    ap.add_argument("--out", default="")
    ap.add_argument("--tag", default="composite")
    a = ap.parse_args()

    mod, cls = DOMAIN[a.domain]["adapter"].split(":")
    adapter = getattr(__import__(mod, fromlist=[cls]), cls)()
    executor = Tau2Executor()
    llm = LLMClient({"llm": llm_cfg(a.domain)})

    trees = sorted(storage.iter_trees(Path(WS + "/" + DOMAIN[a.domain]["trees"])),
                   key=lambda t: t.tree_id)
    banded = [t for t in trees
              if a.min_conditions <= len(t.root.conditions) <= a.max_conditions]
    if a.tree_shard:
        i, nsh = (int(x) for x in a.tree_shard.split("/"))
        banded = [t for j, t in enumerate(banded) if j % nsh == i]
    out = a.out or f"artifacts/{a.domain}_composite_k{a.k}.json"
    print(f"[{a.tag}] {a.domain} k={a.k}: {len(trees)} trees, {len(banded)} in band "
          f"[{a.min_conditions},{a.max_conditions}], target {a.target}", flush=True)
    if not banded:
        raise SystemExit("no trees in the condition band")

    import concurrent.futures as cf
    results, t0, wave = [], time.time(), 0
    admitted = 0
    seen_specs: set = set()
    while admitted < a.target and wave < a.max_waves:
        jobs = [(t, wave * a.combos_per_tree + i, a.k, adapter, executor, llm, a.attempts)
                for t in banded for i in range(a.combos_per_tree)]
        print(f"  wave {wave}: {len(jobs)} cells", flush=True)
        with cf.ThreadPoolExecutor(max_workers=a.workers) as ex:
            for i, r in enumerate(ex.map(run_cell, jobs), 1):
                if r["status"] == "admitted":
                    spec = r["mask"].get("spec_id")
                    if spec in seen_specs:          # identical mask drawn twice
                        r["status"] = "duplicate"
                    else:
                        seen_specs.add(spec)
                        admitted += 1
                results.append(r)
                if i % 50 == 0:
                    print(f"    {i}/{len(jobs)} | admitted {admitted}/{a.target} "
                          f"| {time.time()-t0:.0f}s", flush=True)
                if admitted >= a.target:
                    break
        wave += 1

    adm = [r for r in results if r["status"] == "admitted"]
    summary = {
        "tag": a.tag, "domain": a.domain, "k": a.k, "target": a.target,
        "trees_total": len(trees), "trees_in_band": len(banded),
        "condition_band": [a.min_conditions, a.max_conditions],
        "cells": len(results), "admitted": len(adm),
        "rejected": sum(1 for r in results if r["status"] == "rejected"),
        "errors": sum(1 for r in results if r["status"] == "error"),
        "skipped": sum(1 for r in results if r["status"] == "skipped"),
        "duplicates": sum(1 for r in results if r["status"] == "duplicate"),
        "waves": wave, "wall_s": round(time.time() - t0, 1),
        "samples_per_tree": round(len(adm) / max(len(banded), 1), 2),
        "by_fault": dict(Counter(x for r in adm for x in r["strategy_ids"]).most_common()),
        "distinct_combos": len({r["strategy"] for r in adm}),
        "verdicts": dict(Counter(r.get("verdict") for r in results
                                 if r["status"] in ("rejected", "error")).most_common(12)),
        "llm_usage": getattr(llm, "_usage", {}),
    }
    Path(WS + "/artifacts").mkdir(exist_ok=True)
    with open(WS + "/" + out, "w") as f:
        json.dump({"summary": summary, "results": results}, f, indent=1)
    print(json.dumps(summary, indent=1), flush=True)


if __name__ == "__main__":
    main()
